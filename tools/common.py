def hexrgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb15(c):
    r, g, b = [max(0, min(255, int(round(v)))) for v in c]
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)


def snap15(c):
    """Round an RGB colour to what the GBA can display."""
    return tuple(((max(0, min(255, int(round(v)))) >> 3) << 3) for v in c)


class CFile:
    """Accumulates C definitions plus matching extern declarations."""

    def __init__(self, name):
        self.name = name
        self.body = []
        self.decls = []

    def array(self, ctype, name, data, per_line=16, fmt=None, align=4):
        data = list(data)
        if fmt is None:
            if ctype in ('u8', 's8'):
                fmt = lambda v: '0x%02X' % (v & 0xFF) if ctype == 'u8' else str(v)
            elif ctype in ('u16',):
                fmt = lambda v: '0x%04X' % (v & 0xFFFF)
            elif ctype in ('u32',):
                fmt = lambda v: '0x%08X' % (v & 0xFFFFFFFF)
            else:
                fmt = str
        lines = []
        for i in range(0, len(data), per_line):
            lines.append('  ' + ','.join(fmt(v) for v in data[i:i + per_line]) + ',')
        self.body.append('const %s %s[%d] __attribute__((aligned(%d))) = {\n%s\n};\n'
                         % (ctype, name, len(data), align, '\n'.join(lines)))
        self.decls.append('extern const %s %s[%d];' % (ctype, name, len(data)))

    def raw(self, text, decl=None):
        self.body.append(text)
        if decl:
            self.decls.append(decl)

    def write(self):
        path = os.path.join(OUT, self.name + '.c')
        with open(path, 'w') as f:
            f.write('/* Generated by tools/gen_assets.py - do not edit. */\n')
            f.write('#include "assets.h"\n\n')
            f.write('\n'.join(self.body))
        return self.decls


def pack4bpp_tile(px):
    """px: 8x8 list/array of palette indices 0..15 -> 32 bytes."""
    out = []
    for y in range(8):
        for x in range(0, 8, 2):
            out.append((int(px[y][x]) & 15) | ((int(px[y][x + 1]) & 15) << 4))
    return out


def sprite_to_4bpp(img):
    """img: HxW numpy/2D list of indices. Returns 1D-mapped OBJ tile bytes."""
    h = len(img)
    w = len(img[0])
    out = []
    for ty in range(h // 8):
        for tx in range(w // 8):
            tile = [[img[ty * 8 + y][tx * 8 + x] for x in range(8)] for y in range(8)]
            out += pack4bpp_tile(tile)
    return out


